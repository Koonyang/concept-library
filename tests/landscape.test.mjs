/* 휴대폰에서 첫 탭에 전체 화면 + 가로 고정(설정에서 끌 수 있음) */
import { chromium } from "playwright-core";
import { LIB_ROOT, launchBrowser } from "./lib/browser.mjs";
import { createServer } from "http";
import { readFileSync, existsSync } from "fs";
import { extname, join, normalize } from "path";
const ROOT=LIB_ROOT;
const MIME={".html":"text/html; charset=utf-8",".css":"text/css",".js":"text/javascript",".woff2":"font/woff2",".png":"image/png",".jpg":"image/jpeg",".svg":"image/svg+xml",".webp":"image/webp",".mp3":"audio/mpeg"};
const server=createServer((q,r)=>{const u=decodeURIComponent((q.url||"/").split("?")[0]);const a=normalize(join(ROOT,u==="/"?"/index.html":u));if(!a.startsWith(ROOT)||!existsSync(a)){r.writeHead(404);return r.end();}r.writeHead(200,{"content-type":MIME[extname(a)]||"application/octet-stream"});r.end(readFileSync(a));});
await new Promise(r=>server.listen(0,"127.0.0.1",r)); const BASE="http://127.0.0.1:"+server.address().port+"/";
const b=await launchBrowser(chromium,{args:["--no-sandbox","--use-gl=swiftshader","--enable-webgl","--ignore-gpu-blocklist"]});
let fails=0; const ok=(c,n,o)=>{if(!c)fails++;console.log(c?"PASS":"FAIL",n,o===undefined?"":JSON.stringify(o).slice(0,700));};
const p=await (await b.newContext({viewport:{width:844,height:390}})).newPage(); const errs=[]; p.on("pageerror",e=>errs.push(e.message)); p.on("console",m=>{if(m.type()==="error")errs.push(m.text());});
const ctx=await b.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
const q=await ctx.newPage(); q.on("pageerror",e=>errs.push(e.message));
const spy=()=>q.addInitScript(()=>{ window.__fs=0; window.__lock=null; Element.prototype.requestFullscreen=function(){ window.__fs++; return Promise.resolve(); };
  Object.defineProperty(screen,"orientation",{configurable:true,value:{type:"portrait-primary",lock:o=>{ window.__lock=o; return Promise.resolve(); },addEventListener(){}}}); });
await spy();
await q.goto(BASE); await q.evaluate(()=>localStorage.clear()); await q.goto(BASE); await q.waitForSelector('#ui[data-screen="floors"]',{timeout:20000});
await q.tap("#ui .lobby-head"); await q.waitForTimeout(300);
const r1=await q.evaluate(()=>({fs:window.__fs,lock:window.__lock}));
ok(r1.fs===1&&r1.lock==="landscape","휴대폰 첫 탭 → 전체 화면 + 가로 고정",r1);
await q.tap("#btn-set"); const lbl=await q.$eval('.set-panel [data-k="land"]',e=>e.textContent).catch(()=>"");
ok(/가로 고정/.test(lbl),"설정에 가로 고정 토글",lbl);
await q.tap('.set-panel [data-k="land"]'); await q.reload(); await q.waitForSelector('#ui[data-screen="floors"]');
await q.tap("#ui .lobby-head"); await q.waitForTimeout(300);
const r2=await q.evaluate(()=>({fs:window.__fs,lock:window.__lock}));
ok(r2.fs===0&&r2.lock===null,"가로 고정을 끄면 첫 탭에 아무것도 안 함",r2);
ok(errs.length===0,"오류 없음",errs);
console.log("fails",fails); await b.close(); server.close(); process.exit(fails?1:0);
